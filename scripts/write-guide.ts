// Regenerate docs/CONNECT.md from apps/api/src/lib/guide.ts with production URLs.
import { writeFileSync } from "node:fs";
import path from "node:path";
import { guideMarkdown } from "../apps/api/src/lib/guide";
import { ROOT } from "./env";
const api = process.argv[2] ?? "https://api.operis.live";
writeFileSync(path.join(ROOT, "docs/CONNECT.md"), `<!-- generated by scripts/write-guide.ts; edit apps/api/src/lib/guide.ts -->\n${guideMarkdown(api)}`);
console.log(`wrote docs/CONNECT.md for ${api}`);
